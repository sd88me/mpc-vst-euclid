#!/usr/bin/env python3
"""vst/params.json -> src/sdk/params_gen.h: the parameter table of the SDK front end (src/sdk/EuclidierPlugin.cpp).
Order = vst/params.json = vst/params.lock (checked): the VST parameter index that saved projects and skins bind to. Append only.
The 669 of the 1.x build come first; what 2.0 added (stepper arrows, the view, hand-made patterns, touch areas) is appended in vst/params.json."""
import json, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst/params.json")))["params"]
lock = [l.strip() for l in open(os.path.join(ROOT, "vst/params.lock")) if l.strip()]
keys = [p["key"] for p in P]
if keys[:len(lock)] != lock:
    raise SystemExit("params.json no longer starts with params.lock: the order is frozen (append only)")
index = {k: i for i, k in enumerate(keys)}
TRIGGERS = ("rand_go", "preset_load", "preset_save")   # write-only engine actions: never saved, never replayed
# what a fresh sequencer holds (src/core/euclid_core.h), so the host shows sensible values from the first moment
DEFAULTS = {"steps": 16, "fill": 4, "gate": 65, "ch": 1, "vel": 96, "note": 36, "div": 1, "mode": 1}
# ... and what sendDefaults() in EuclidierPlugin.cpp then sets: lanes 1-4 on with a pattern each. These MUST be right from the first
# moment for parameter 0 (l1_enable): the host reads it at start and writes the same value back after loading, which switched lane 1 off.
PATTERNS = {1: (16, 4), 2: (8, 3), 3: (12, 5), 4: (16, 5)}
def default_of(k, lo):
    m = re.match(r"^(?:l(\d)|sel)_(\w+)$", k)
    if not m: return lo
    lane, f = int(m.group(1) or 1), m.group(2)   # sel_ = lane 1, the one selected at start
    if f == "enable": return 1 if lane in PATTERNS else 0
    if f in ("steps", "fill") and lane in PATTERNS: return PATTERNS[lane][f == "fill"]
    return DEFAULTS.get(f, lo)
# flags: 1 momentary (fires on 0 -> 1, drops back), 2 engine trigger, 8 choice, 16 stepper arrow (moves another parameter),
# 32 display cell (the plugin owns it), 64 selected-lane mirror ("sel_<x>" = the selected lane's "l<N>_<x>"), 128 saved but never shown or automated
out = ["/* generated by tools/gen_sdk_params.py: do not edit. One row per parameter, in the frozen VST order. */", "#pragma once",
       "enum { kMomentary = 1, kTrigger = 2, kChoice = 8, kStepper = 16, kCell = 32, kSelMirror = 64, kHidden = 128, kTap = 256 };",
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget, stepDelta; };", ""]
rows, optsets = [], {}
for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n, tgt, delta = 0, "nullptr", 0, -1, 0
    if "options" in p:
        fl |= 8
        opts = tuple(p["options"])
        if opts not in optsets:   # 540 cells share five option lists
            optsets[opts] = "ch_%d" % len(optsets)
            out.append("static const char *const %s[] = {%s};" % (optsets[opts], ", ".join(json.dumps(o) for o in opts)))
        ch, n = optsets[opts], len(opts)
        lo, hi = 0, len(opts) - 1
        d = min(max(int(p.get("default", default_of(k, 0))), lo), hi)
    elif p.get("momentary") or k in TRIGGERS:
        lo, hi, d = 0, 1, 0
        fl |= 1
        if k in TRIGGERS: fl |= 2
        if "step_of" in p:
            fl |= 16
            tgt, delta = index[p["step_of"]], int(p["step_delta"])
    else:
        lo, hi = p["min"], p["max"]
        d = min(max(default_of(k, lo), lo), hi)
    if re.match(r"^(g\d+_\d+_\d+|c\d+_\d+)$", k): fl |= 32
    if k.startswith("sel_") and not (fl & 1): fl |= 64
    if re.match(r"^m\d_(on|a|b)$", k): fl |= 128
    if re.match(r"^(tg\d_\d+|ct_\d+)$", k): fl |= 256
    rows.append('    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %d},' % (json.dumps(k), json.dumps(p["name"]), repr(float(lo)) + "f", repr(float(hi)) + "f",
                                                                 repr(float(d)) + "f", fl, ch, n, tgt, delta))
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};", "static const int kNumParams = %d;" % len(P), ""]
os.makedirs(os.path.join(ROOT, "src/sdk"), exist_ok=True)
open(os.path.join(ROOT, "src/sdk/params_gen.h"), "w").write("\n".join(out))
print("src/sdk/params_gen.h: %d params" % len(P))
